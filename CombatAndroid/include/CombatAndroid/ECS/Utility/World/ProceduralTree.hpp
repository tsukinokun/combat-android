//-------------------------------------------------------------
//! @file    ProceduralTree.hpp
//! @brief   木の形をプログラムで組み立てる関数の宣言
//! @note    素材のモデルを使わず、種（seed）から幹・枝・葉の塊のメッシュを作る。
//!          同じ種と同じパラメータなら、いつ作っても同じ木になる。
//!          描画（DrawCommandへの積み方）や配置はTreeFieldSystemが受け持ち、ここは形だけを作る
//-------------------------------------------------------------
#pragma once
#include <Tsukino/GraphicsCommon/Mesh/MeshData.hpp>

#include <cstdint>
#include <vector>
// 名前空間 : CombatAndroid::ECS
namespace CombatAndroid::ECS {
    //-------------------------------------------------------------
    //! @struct TreeShapeParams
    //! @brief  1本の木の形を決める値（長さはワールド単位。1ユニット≒1cm）
    //-------------------------------------------------------------
    struct TreeShapeParams {
        std::uint32_t seed = 1;    //!< 形の乱数の種

        //-------------------------------------------------------------
        // 幹と枝
        //-------------------------------------------------------------
        float trunkHeight   = 260.0f;    //!< 主幹の長さ
        float trunkRadius   = 20.0f;     //!< 主幹の根元の半径
        int   branchDepth   = 3;         //!< 枝分かれの深さ（主幹を0として、何段まで枝を出すか）
        int   childCountMin = 2;         //!< 1本の枝から出る子の枝の数（最小）
        int   childCountMax = 3;         //!< 同じく最大
        float lengthRatio   = 0.62f;     //!< 子の枝の長さ（親に対する比）
        float radiusRatio   = 0.58f;     //!< 子の枝の根元の太さ（親の根元に対する比）
        float spreadAngle   = 0.65f;     //!< 子の枝が親の向きから開く角度（ラジアン）
        float bend          = 0.12f;     //!< 枝の曲がり具合（節ごとに向きをずらす量。ラジアン）
        float upwardPull    = 0.25f;     //!< 枝が上へ向かおうとする強さ（0で開いたまま、1で真上へ寄る）

        //-------------------------------------------------------------
        // 葉（枝の先ごとに、葉の絵を貼った小さな板＝葉カードを茂みの形に散らす）
        //-------------------------------------------------------------
        float canopyRadius    = 62.0f;     //!< 枝先1つぶんの茂みの半径
        int   leafCardsPerTip = 40;        //!< 枝先1つあたりの葉カードの枚数
        float leafCardSize    = 46.0f;     //!< 葉カード1枚の一辺
        float canopySquash    = 0.8f;      //!< 茂みの縦のつぶれ具合（1で球、小さいほど平たい）

        //-------------------------------------------------------------
        // メッシュの細かさ
        //-------------------------------------------------------------
        int radialSegments = 7;    //!< 枝の断面の角数
        int lengthSegments = 4;    //!< 枝1本の節の数（多いほど曲がりがなめらか）
    };

    //-------------------------------------------------------------
    //! @struct TreeMeshes
    //! @brief  組み立てた木1本ぶんのメッシュ
    //! @note   幹と葉は色が違うので、別のメッシュにして別のマテリアルで描く。
    //!         幹はUVのvに「下0→上1」の高さの割合を入れてあり、縦のグラデーションテクスチャで色を付ける。
    //!         葉は葉テクスチャのアトラス（2×2の4種類）のUVを持ち、テクスチャのアルファで葉の形にくり抜いて描く
    //-------------------------------------------------------------
    struct TreeMeshes {
        Tsukino::GraphicsCommon::MeshData trunk;     //!< 幹と枝（なめらかな陰影）
        Tsukino::GraphicsCommon::MeshData canopy;    //!< 葉カード（法線は茂みの中心から外向き。ふんわりした陰影になる）
        float trunkRadius = 0.0f;                    //!< 主幹の根元の半径（当たり判定の太さに使う）
        float height      = 0.0f;                    //!< 木全体の高さ（根元から葉の一番上まで）
    };

    //-------------------------------------------------------------
    //! @brief  木を1本組み立てる
    //! @param  params [in] 形を決める値
    //! @return 幹と葉のメッシュ（根元が原点、上が+Y）
    //-------------------------------------------------------------
    [[nodiscard]]
    TreeMeshes BuildProceduralTree(const TreeShapeParams& params);

    //-------------------------------------------------------------
    //! @struct LeafAtlasParams
    //! @brief  葉カードに貼る葉テクスチャ（2×2のアトラス）の作り方
    //-------------------------------------------------------------
    struct LeafAtlasParams {
        std::uint32_t seed          = 1;             //!< 葉の配置と色の乱数の種
        int           size          = 256;           //!< テクスチャの一辺（ピクセル。1マスはその半分）
        int           leavesPerTile = 9;             //!< 1マスに描く葉の数（少なく大きくするほど、遠くでちらつきにくい）
        float         darkColor[3]  = {0.05f, 0.16f, 0.05f};    //!< 葉の色の暗い側
        float         lightColor[3] = {0.24f, 0.48f, 0.12f};    //!< 葉の色の明るい側
    };

    //-------------------------------------------------------------
    //! @brief  葉テクスチャのピクセルを作る
    //! @param  params [in] 作り方
    //! @return RGBA8のピクセル（size×size×4バイト。先頭がv=0の行）。葉の外はアルファ0
    //! @note   先の尖った葉を、マスごとに少しずつ向きと大きさを変えて重ねて描く。
    //!         葉ごとに暗い側〜明るい側の色を選び、葉脈と縁を少し暗くして葉らしく見せる
    //-------------------------------------------------------------
    [[nodiscard]]
    std::vector<std::uint8_t> BuildLeafAtlasPixels(const LeafAtlasParams& params);
}    // namespace CombatAndroid::ECS
