#pragma once
#include <array>
#include <hlsl++.h>
// 名前空間 : CombatAndroid::ECS
namespace CombatAndroid::ECS {
    //--------------------------------------------------------------
    //! 草の種類ごとの見た目
    //! @note 位置の抽選と同じく、頂点シェーダーが「その草が生えている
    //!       パッチ（GrassFieldComponent::patchSize四方の区画）」の
    //!       ハッシュから種を選ぶ。CPU側はこの配列を種ごとの見た目として
    //!       渡すだけで、どの草がどの種になるかは関知しない
    //--------------------------------------------------------------
    struct GrassSpecies {
        float height     = 34.0f;    // この種の高さ
        float widthScale = 1.0f;     // GrassFieldComponent::bladeWidth に掛ける倍率

        hlslpp::float3 rootColor = hlslpp::float3(0.10f, 0.22f, 0.06f);    // 根元の色（linear）
        hlslpp::float3 tipColor  = hlslpp::float3(0.42f, 0.62f, 0.20f);    // 先端の色（linear）
    };

    //--------------------------------------------------------------
    //! 地面に生える草の設定
    //! @note AmbientParticleComponent / FogComponent と同じく
    //!       「アタッチする／しない」で機能そのもののON/OFFを表現する。
    //!       シーンに複数あっても最初の1つだけが使われる。
    //!
    //!       草はAmbientParticleと同じく、1本あたりのメモリを持たない。
    //!       刃のメッシュは9頂点のものが1本だけ作られ、全部の草がそれを
    //!       インスタンス描画で共有する。位置・向き・高さ・揺れの位相は
    //!       すべて「その草が生えているセルのワールド座標」のハッシュから
    //!       毎フレーム計算し直すため、bladeCount を増やしてもメモリは
    //!       1バイトも増えない（増えるのは頂点シェーダーの実行回数だけ）。
    //!
    //!       ハッシュの種にワールド座標を使うのが肝で、これにより
    //!       「同じ場所には常に同じ草が生える」＝カメラが動いても草は
    //!       地面に固定されたまま、という状態になる。カメラ番号や
    //!       インスタンス番号を種にすると草が世界を滑ってしまう。
    //!
    //!       描画は通常のGBufferパスを通るので、ディファードライティング・
    //!       ポイントライト・影・フォグはすべて自動で乗る。
    //!
    //!       既定値は「1ユニット = 1cm」のシーンを想定している。長さの次元を
    //!       持つ値（fieldSize / species[].height / bladeWidth / patchSize /
    //!       gustWavelength / gustSpeed / playerPushRadius）はワールドスケールに
    //!       合わせて入れ直すこと。
    //--------------------------------------------------------------
    struct GrassFieldComponent {
        //----------------------------------------------------------
        // 有効・無効
        //----------------------------------------------------------
        bool enabled = true;    // false なら描画コマンドを積まない

        //----------------------------------------------------------
        // 量と範囲
        //----------------------------------------------------------
        //! @note 密度は bladeCount / (fieldSize / 100)^2 本/m^2。
        //!       fieldSize はカメラに追従する正方形の一辺で、これを広げると
        //!       同じ本数が薄く散らばる（＝密度が下がる）関係にある。
        unsigned int bladeCount = 15000;      // 草の本数。上限は kMaxGrassBlades でクランプされる
        float        fieldSize  = 1600.0f;    // カメラを中心に草を敷き詰める正方形の一辺
        unsigned int seed       = 20260908;   // 配置を決める乱数シード

        //----------------------------------------------------------
        // 刃の形
        //----------------------------------------------------------
        //! 草の種類。高さ・幅の倍率・色をここで3種ぶん持つ
        //! @note 種を増やすには GrassSpecies 配列を伸ばすだけでは足りない。
        //!       CBufferGrass（GrassFieldSystem.hpp）・Grass.vs.hlsl・
        //!       GetGradientSRV（GrassFieldSystem.cpp）がいずれも「3種」を
        //!       前提に float4.xyz / グラデーションテクスチャの3段を
        //!       決め打ちしているため、そちらも合わせて直すこと
        std::array<GrassSpecies, 3> species = {{
            {34.0f, 1.00f, hlslpp::float3(0.10f, 0.22f, 0.06f), hlslpp::float3(0.42f, 0.62f, 0.20f)},    // 標準の緑
            {22.0f, 0.85f, hlslpp::float3(0.16f, 0.17f, 0.05f), hlslpp::float3(0.55f, 0.52f, 0.16f)},    // 丈の低い、乾いた黄金色
            {46.0f, 1.15f, hlslpp::float3(0.05f, 0.13f, 0.05f), hlslpp::float3(0.18f, 0.42f, 0.20f)},    // 丈の高い、濃い緑
        }};

        float bladeWidth     = 3.5f;     // 根元の幅の基準値。各種の widthScale がこれに掛かる
        float heightVariance = 0.35f;    // 高さのばらつき（種ごとの高さに対して。0で一定、1で0〜2倍の範囲）
        float groundHeight   = 0.0f;     // 草が生える地面の高さ（Y）

        //! フィールドの外周で草の幅を何倍まで太らせるか（0で一定）
        //! @note fieldSize を広げると同じ本数が薄く散らばって密度が落ちる。
        //!       遠くの草は画面上で数ピクセルしかないので、幅を増やしてやると
        //!       隙間が埋まり、本数を増やさずに草原が途切れず続いて見える。
        //!       手前では効かないよう距離の二乗で掛かる
        float distantWidthBoost = 2.5f;

        //! 種が切り替わる塊のおおよその大きさ（一辺）
        //! @note 草1本ごとにバラバラに種を選ぶと砂嵐のようなノイズに見えるため、
        //!       この大きさの正方形パッチ単位でワールド座標をハッシュし、
        //!       パッチごとにまとめて同じ種を選ぶ。群生っぽい塊で生える
        float patchSize = 400.0f;

        //----------------------------------------------------------
        // 風
        //----------------------------------------------------------
        //! @note 3つの成分を足して風を作る。
        //!       常時なびき : 全体が風下へ傾いた定常状態
        //!       突風       : 風の波が草原を走っていく。波の位相をワールド座標から
        //!                    決めるので、草原全体が一斉に揺れることがない
        //!       そよぎ     : 草ごとにバラバラな細かい震え
        //!
        //!       FogComponent も windDirection / windSpeed を持っており、
        //!       霧のノイズがその向きへ流れている。草だけ別方向になびくと
        //!       世界が壊れるので、両方に同じ向きを入れること。
        hlslpp::float3 windDirection = hlslpp::float3(1.0f, 0.0f, 0.3f);    // 風の向き（Systemが正規化して転送する）
        float          windStrength  = 0.25f;                               // 常時なびく強さ（0で直立、1で真横）

        float gustWavelength = 900.0f;    // 突風の波の間隔
        float gustSpeed      = 260.0f;    // 突風の波が進む速さ（ワールド単位/秒）
        float gustStrength   = 0.35f;     // 突風で追加される傾きの強さ

        float swaySpeed     = 2.2f;     // 草ごとの細かい震えの角速度（rad/秒）
        float swayStrength  = 0.08f;    // 同じく震えの強さ

        //----------------------------------------------------------
        // プレイヤーのかき分け
        //----------------------------------------------------------
        //! @note 追従対象は CharacterControllerComponent を持つ最初の
        //!       エンティティ。半径はキャラクターのカプセル半径より
        //!       大きめにしておくと、足元だけでなく体の周りが押し広げられる。
        float playerPushRadius   = 90.0f;    // この距離まで草を押しのける
        float playerPushStrength = 1.2f;     // 押しのける強さ

        //----------------------------------------------------------
        // フェード
        //----------------------------------------------------------
        //! @note fieldSize の外周では草の高さを0へ縮めて消す。高さ0の草は
        //!       面積がゼロになり1ピクセルも塗らないので、境界で唐突に
        //!       草が現れるのを防ぎつつ描画量も無駄にしない。
        //!       1.0 にすると境界まで縮まないので、必ず 1.0 未満にすること。
        float fadeStartRatio = 0.70f;    // 中心からこの比率より外で消えていく
    };
}    // namespace CombatAndroid::ECS
