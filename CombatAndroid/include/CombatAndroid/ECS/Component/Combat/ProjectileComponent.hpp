#pragma once
#include <Tsukino/Core/ECS/Entity/Entity.hpp>

#include <hlsl++.h>

#include <vector>
// 名前空間 : CombatAndroid::ECS
namespace CombatAndroid::ECS {
    //-------------------------------------------------------------
    //! @struct ProjectileComponent
    //! @brief  前方へ飛んでいく攻撃判定（バトルアックスの溜め攻撃で出る斬撃弾）に付与するコンポーネント。
    //!         ProjectileSystemが毎フレームdirection方向へ進め、前フレーム位置→今フレーム位置を
    //!         芯線とするカプセルで敵とのオーバーラップを取る。見た目はEffectComponentが担当し、
    //!         このエンティティのTransformへ追従する（エフェクト自体は座標移動を持たない）
    //! @note   ダメージとスキル倍率は発射した瞬間に確定させてここへ焼き込む。飛翔中に武器を
    //!         持ち替えたり所有者が死んだりしても、飛んでいる弾の威力が変わらないようにするため
    //-------------------------------------------------------------
    struct ProjectileComponent {
        Tsukino::ECS::Entity owner = entt::null;    //!< 撃った側。ヒットストップと嫉妬の回復先に使う

        hlslpp::float3 direction = hlslpp::float3(0.0f, 0.0f, 1.0f);    //!< 進行方向（正規化済み・水平）
        float          speed     = 900.0f;                               //!< 飛翔速度（ユニット/秒）

        float damage = 0.0f;    //!< 命中時に与える実ダメージ（倍率適用後の確定値）

        //-------------------------------------------------------------
        // 当たり判定は「前フレーム位置→今フレーム位置」を芯線とするカプセル。
        // 武器スイングのサブステップ判定（CombatSystem）と同じく、速い移動で敵を
        // 跨いですり抜けるのを防ぐ
        //-------------------------------------------------------------
        float radius = 60.0f;    //!< 判定カプセルの半径（斬撃波の見た目の太さに合わせる）

        float remainingLifetime = 1.0f;      //!< 残り寿命（秒）。0以下で破棄する
        float traveledDistance  = 0.0f;      //!< 発射地点からの累計飛距離
        float maxDistance       = 1200.0f;   //!< この距離を超えたら破棄する（寿命と併用し、どちらか早い方で消える）

        std::vector<Tsukino::ECS::Entity> hitEnemies;    //!< この弾が既にヒットさせた敵（貫通する場合に同じ敵への二重ヒットを防ぐ）

        //-------------------------------------------------------------
        // 貫通するか。溜めの浅い（1段階目の）斬撃弾は1体で止まり、深く溜めたものだけが
        // 群れを薙ぎ払える、という段階差を出すために弾ごとに切り替える
        // （どの段階から貫通するかはWeaponComponent::projectilePierceMinChargeStageが持つ）
        //-------------------------------------------------------------
        bool piercing = true;    //!< falseなら最初にダメージを与えた1体で消滅する

        //-------------------------------------------------------------
        // スキル「嫉妬」。武器のアタック単位の上限（WeaponComponent::lifeStealHealedThisAttack）とは
        // 別枠で、弾1発ぶんの吸収量を持つ
        //-------------------------------------------------------------
        float lifeStealRatio  = 0.0f;    //!< 与ダメージのうちHPへ変換する割合（0なら吸収しない）
        float lifeStealHealed = 0.0f;    //!< この弾で既に吸収した量（上限判定に使う）
    };
}    // namespace CombatAndroid::ECS
